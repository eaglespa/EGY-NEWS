const MAP: Record<string, string> = {
  "—": "-", "–": "-", "“": '"', "”": '"', "‘": "'", "’": "'",
  "·": ".", "…": "...", "é": "e", "è": "e", "ê": "e", "ë": "e",
  "à": "a", "â": "a", "ä": "a", "á": "a", "ã": "a", "å": "a",
  "î": "i", "ï": "i", "í": "i", "ì": "i",
  "ô": "o", "ö": "o", "ò": "o", "ó": "o", "õ": "o", "ø": "o",
  "û": "u", "ü": "u", "ù": "u", "ú": "u",
  "ç": "c", "ñ": "n", "ß": "ss", "æ": "ae", "œ": "oe", "š": "s",
  "ż": "z", "ą": "a", "ę": "e", "ł": "l", "ń": "n", "ś": "s",
  "ź": "z", "ı": "i", "ğ": "g", "ş": "s",
};

export function toAscii(input: string): string {
  return input
    .split("")
    .map((c) => MAP[c] ?? c)
    .join("")
    .replace(/[^\x20-\x7E]/g, "");
}
